-- الحماية الحقيقية من السباق بين جهازين تكون في قاعدة البيانات، وليس في
-- فحص الواجهة فقط. تسجيل الخروج يحرر القيد عبر ended_at.
create unique index if not exists idx_work_shifts_one_open_per_worker
  on work_shifts (worker_id)
  where ended_at is null;

comment on index idx_work_shifts_one_open_per_worker is
  'قفل جهاز واحد لكل عامل: لا يسمح بحصتين مفتوحتين حتى مع تسجيل دخول متزامن من جهازين';
